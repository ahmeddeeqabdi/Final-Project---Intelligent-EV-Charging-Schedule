CREATE TABLE app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE user_constraints (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE,
    default_battery_capacity DOUBLE PRECISION NOT NULL,
    default_max_power DOUBLE PRECISION NOT NULL,
    default_preference_weight DOUBLE PRECISION NOT NULL,
    price_area VARCHAR(3) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_user_constraints_user
        FOREIGN KEY (user_id) REFERENCES app_users (id) ON DELETE CASCADE
);

CREATE TABLE energy_prices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hour_utc TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    price_area VARCHAR(3) NOT NULL,
    price_dkk_per_kwh DOUBLE PRECISION NOT NULL,
    CONSTRAINT uq_energy_prices_hour_area UNIQUE (hour_utc, price_area)
);

CREATE TABLE co2_intensity (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    timestamp_utc TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    price_area VARCHAR(3) NOT NULL,
    g_per_kwh DOUBLE PRECISION NOT NULL,
    CONSTRAINT uq_co2_intensity_timestamp_area UNIQUE (timestamp_utc, price_area)
);

CREATE TABLE schedule_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    algorithm VARCHAR(32) NOT NULL,
    total_predicted_cost DOUBLE PRECISION NOT NULL,
    total_predicted_emissions DOUBLE PRECISION NOT NULL,
    degraded_enabled BOOLEAN NOT NULL,
    degraded_reason VARCHAR(255),
    degraded_source VARCHAR(255) NOT NULL,
    degraded_data_age_hours BIGINT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_schedule_results_user
        FOREIGN KEY (user_id) REFERENCES app_users (id) ON DELETE CASCADE
);

CREATE TABLE schedule_slots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schedule_result_id BIGINT NOT NULL,
    slot_timestamp TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    power_draw DOUBLE PRECISION NOT NULL,
    current_price DOUBLE PRECISION NOT NULL,
    current_co2 DOUBLE PRECISION NOT NULL,
    CONSTRAINT fk_schedule_slots_result
        FOREIGN KEY (schedule_result_id) REFERENCES schedule_results (id) ON DELETE CASCADE
);

CREATE INDEX idx_schedule_results_user_created
    ON schedule_results (user_id, created_at DESC);

CREATE INDEX idx_schedule_slots_result
    ON schedule_slots (schedule_result_id);
